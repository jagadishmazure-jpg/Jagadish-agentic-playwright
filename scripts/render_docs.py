"""Render docs/results.md and the README results table from evidence/*.json.

  python scripts/render_docs.py          rewrite the files
  python scripts/render_docs.py --check  exit 1 if the committed docs drift from the evidence (CI)
Every number in those sections comes from a recorded run; nothing is typed by hand.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EV = ROOT / "evidence"
START, END = "<!-- results:start -->", "<!-- results:end -->"


def load(name: str) -> dict:
    return json.loads((EV / name).read_text())


def table() -> str:
    a, h, f, b = load("browser-agent.json"), load("healing.json"), load("flakiness.json"), load("flakiness-before-fix.json")
    c = load("promptfoo-evals.json")
    per_rule = ", ".join(f"{k} {v['passed']}/{c['cases']}" for k, v in c["per_rule"].items())
    blocks = ", ".join(f"{k} {v}" for k, v in sorted(a["guardrail_blocks"].items()))
    rows = [
        ("Browser agent: feasible approved tasks completed", f"{a['success']}/{a['feasible_approved_tasks']}", f"{a['runs']} seeded runs, {a['model']}; measures the harness, not a real LLM"),
        ("Browser agent: steps per successful run", f"mean {a['steps_mean_successful']}, median {a['steps_median_successful']}", "MCP tool calls"),
        (
            "Browser agent: injection attempts blocked",
            f"{a['injection_attempts_blocked']}/{a['injection_attempts_by_model']}",
            f"obey rate {a['obey_injection_rate']}; {a['injection_pages_visited']} visits to poisoned pages",
        ),
        ("Browser agent: secret values seen by the model", str(a["secret_values_seen_by_model"]), "secrets go through fill_secret only"),
        (
            "Browser agent: approvals requested / granted / denied",
            f"{a['approvals']['requested']} / {a['approvals']['granted']} / {a['approvals']['denied']}",
            f"denied runs that still completed: {a['denied_runs_that_still_completed']}",
        ),
        ("Browser agent: guardrail blocks", blocks, f"infeasible tasks stopped by step budget: {a['infeasible_stopped_by_budget']}/{a['infeasible_tasks']}"),
        (
            "Offline healer (broken + removed locators)",
            f"{h['correct_heal']} correct, {h['missed_heal']} missed, {h['false_heal']} false, {h['correct_refusal']} correct refusals",
            f"{h['cases']} cases ({h['broken_locator_cases']} broken, {h['removed_element_cases']} removed)",
        ),
        ("Agent-app flakiness, before fix", f"{b['failed_executions']}/{b['executions']} failed, {len(b['flaky_tests'])} flaky test", f"{b['tests']} tests x {b['repeat_each']} repeats, retries 0"),
        ("Agent-app flakiness, after fix", f"{f['failed_executions']}/{f['executions']} failed", f"wall time {f['wall_seconds']} s"),
        (
            "Copy evals (promptfoo): clean descriptions",
            f"{c['cases_passed']}/{c['cases']}",
            f"{c['rules']} named rules, {c['assertions']} checks; offline fixture provider, so this checks the rules, not a model",
        ),
        ("Copy evals: cases failing exactly their planted rules", f"{c['cases_matching_expected_failures']}/{c['cases']}", "synthetic descriptions, some written to break rules"),
        ("Copy evals: per-rule pass rate", per_rule, "one promptfoo metric per rule"),
        (
            "Copy evals: failures that name the rule and quote the text",
            f"named {c['failure_reasons_in_named_format']}/{c['assertions_failed']}, bare booleans {c['bare']['failure_reasons_with_evidence']}/{c['bare']['assertions_failed']}",
            f"bare run: {c['bare']['failure_reasons_starting_custom_function_returned_false']} reasons say only 'Custom function returned false', "
            f"{c['bare']['per_rule_metrics_reported']} per-rule metrics",
        ),
    ]
    out = ["| Measure | Result | Notes |", "|---|---|---|"]
    out += [f"| {m} | {r} | {n} |" for m, r, n in rows]
    return "\n".join(out)


def results_md() -> str:
    return (
        "# Results\n\n"
        "Generated by `scripts/render_docs.py` from `evidence/*.json`; CI fails if this file drifts. "
        "All numbers come from local runs on the box described in [limitations.md](limitations.md). "
        "Nothing ran in Azure.\n\n" + table() + "\n\n"
        "Sample audit logs and replay specs for three runs are in `evidence/sample-runs/`.\n"
    )


def render() -> dict[Path, str]:
    readme = ROOT / "README.md"
    text = readme.read_text()
    new_readme = re.sub(re.escape(START) + ".*?" + re.escape(END), START + "\n" + table() + "\n" + END, text, flags=re.S)
    return {ROOT / "docs" / "results.md": results_md(), readme: new_readme}


def main() -> int:
    check = "--check" in sys.argv
    drift = []
    for path, content in render().items():
        current = path.read_text() if path.exists() else ""
        if current != content:
            if check:
                drift.append(path.relative_to(ROOT))
            else:
                path.write_text(content)
    if drift:
        print("doc drift:", ", ".join(map(str, drift)), "- run python scripts/render_docs.py")
        return 1
    print("docs match evidence" if check else "docs rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
